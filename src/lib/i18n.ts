export function t(lang: Lang, key: string): string {
  return dict[lang][key] ?? dict.en[key] ?? key
}

export function getLang(): Lang {
  const stored = localStorage.getItem('anjam.lang')
  if (stored === 'fa' || stored === 'en') return stored
  return (navigator.language || 'en').toLowerCase().startsWith('fa') ? 'fa' : 'en'
}

export function applyLang(lang: Lang): void {
  localStorage.setItem('anjam.lang', lang)
  document.documentElement.lang = lang
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr'
}

const WEEKDAYS_EN = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']

export function fmtDate(lang: Lang, iso: string): string {
  const d = new Date(iso)
  if (lang === 'fa') {
    try {
      return new Intl.DateTimeFormat('fa-IR', { month: 'long', day: 'numeric', weekday: 'short' }).format(d)
    } catch {
      /* fall through */
    }
  }
  return `${WEEKDAYS_EN[d.getDay()]} ${d.getDate()}/${d.getMonth() + 1}`
}

export function fmtTime(lang: Lang, iso: string): string {
  const d = new Date(iso)
  if (lang === 'fa') {
    try {
      return new Intl.DateTimeFormat('fa-IR', { hour: '2-digit', minute: '2-digit', hour12: false }).format(d)
    } catch {
      /* fall through */
    }
  }
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
}
